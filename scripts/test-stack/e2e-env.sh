#!/usr/bin/env bash
# Write the .env.local an E2E run against StrummyTest uses, on uwh.
#
#   scripts/test-stack/e2e-env.sh <out-file>
#
# Starts from the dev E2E env (~/.strummy-e2e/.env.local: AI, Google, PostHog …),
# drops EVERY Supabase and Postgres line — that file also holds production's URL
# and keys — and points all the Supabase names the app and the tests read at
# StrummyTest: whichever one a code path picks (LOCAL_*, the plain names, the
# service role), it gets the test stack. Nothing in the output can reach
# production; the last check refuses to finish if a production address is left.
#
# Role-account passwords are the shared test password (e2e-accounts.sql), never
# printed. The output is mode 600 and stays on uwh.
set -euo pipefail

OUT="${1:?usage: e2e-env.sh <out-file>}"
DIR="${STRUMMY_TEST_DIR:-$HOME/strummy-test}"
SOURCE="${STRUMMY_E2E_ENV:-$HOME/.strummy-e2e/.env.local}"
URL="${STRUMMY_TEST_API_URL:-http://192.168.1.75:57321}"

# shellcheck source=/dev/null
. "$DIR/supabase/.env"
# shellcheck source=/dev/null
. "$DIR/test-users.env"
for v in SUPABASE_AUTH_JWT_SECRET SUPABASE_AUTH_PUBLISHABLE_KEY SUPABASE_AUTH_SECRET_KEY STRUMMY_TEST_USERS_PASSWORD; do
  [ -n "${!v:-}" ] || { echo "missing $v in $DIR" >&2; exit 1; }
done

umask 077
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT
{
  echo "# Generated by scripts/test-stack/e2e-env.sh — E2E against StrummyTest. Do not commit."
  grep -vE '^[[:space:]]*(export[[:space:]]+)?[A-Z_]*(SUPABASE|POSTGRES)[A-Z_]*=' "$SOURCE" || true
  echo
  echo "# StrummyTest (scripts/test-stack/)"
  for name in NEXT_PUBLIC_SUPABASE_LOCAL_URL NEXT_PUBLIC_SUPABASE_URL; do echo "$name=$URL"; done
  for name in NEXT_PUBLIC_SUPABASE_LOCAL_ANON_KEY NEXT_PUBLIC_SUPABASE_ANON_KEY SUPABASE_ANON_KEY \
    NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY SUPABASE_PUBLISHABLE_KEY; do
    echo "$name=$SUPABASE_AUTH_PUBLISHABLE_KEY"
  done
  for name in SUPABASE_LOCAL_SERVICE_ROLE_KEY SUPABASE_SERVICE_ROLE_KEY SUPABASE_SECRET_KEY; do
    echo "$name=$SUPABASE_AUTH_SECRET_KEY"
  done
  echo "SUPABASE_JWT_SECRET=$SUPABASE_AUTH_JWT_SECRET"
  echo
  echo "# The four role accounts (e2e-accounts.sql) and the copy's own accounts share one password."
  for role in ADMIN TEACHER STUDENT PARENT; do echo "TEST_${role}_PASSWORD=$STRUMMY_TEST_USERS_PASSWORD"; done
  echo "E2E_COPY_PASSWORD=$STRUMMY_TEST_USERS_PASSWORD"
  echo "E2E_TARGET=test"
} >"$TMP"

# Fail closed: no production host or port may survive into the file.
if grep -qE 'db\.strummy\.online|strummy-db\.|:5432[12]([^0-9]|$)' "$TMP"; then
  echo "REFUSING: a production address is still in the generated env (source: $SOURCE)" >&2
  exit 1
fi
mv "$TMP" "$OUT"
trap - EXIT
echo "wrote $OUT ($(grep -c '=' "$OUT") variables; Supabase → $URL)"

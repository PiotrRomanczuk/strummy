/**
 * Anonymisation SQL for the StrummyTest stack — an anonymised copy of production.
 *
 * `anonymize.rules.json` classifies every column of every public table; this
 * module turns it into one transaction of TRUNCATE + UPDATE statements and
 * appends `anonymize-auth.sql` (auth schema + the final verification). A
 * column missing from the rules is an error, never a silent "keep": see
 * `unclassified()` and `anonymize.unit.test.ts`.
 */

export const ACTIONS = [
  'keep',
  'null',
  'text',
  'json',
  'name',
  'first_name',
  'last_name',
  'name_profile',
  'email_profile',
  'email_invite',
  'email_parent',
] as const;
export type Action = (typeof ACTIONS)[number];

export type TableRule = { truncate: true } | Partial<Record<Action, string[]>>;
export interface Rules {
  partitions: Record<string, string>;
  tables: Record<string, TableRule>;
}

export const TEST_EMAIL_DOMAIN = 'test.strummy.invalid';
const IDENT = /^[a-z_][a-z0-9_]*$/;

const hash = (expr: string, n = 12) => `substr(md5((${expr})::text), 1, ${n})`;
const unlessNull = (c: string, expr: string) => `CASE WHEN ${c} IS NULL THEN NULL ELSE ${expr} END`;
const email = (prefix: string, key: string) =>
  `'${prefix}-' || ${hash(key)} || '@${TEST_EMAIL_DOMAIN}'`;

/** The replacement for one column, or null for 'keep'. */
export function expressionFor(action: Action, column: string): string | null {
  const c = `"${column}"`;
  switch (action) {
    case 'keep':
      return null;
    case 'null':
      return 'NULL';
    case 'text':
      // Same length as the original, so layouts still look like real data.
      return unlessNull(
        c,
        `left(repeat('Lorem ipsum dolor sit amet. ', 1 + length(${c}) / 28), greatest(length(${c}), 1))`
      );
    case 'json':
      // Typed: inside CASE an untyped '{}' resolves to text, which a jsonb column refuses.
      return unlessNull(c, `'{}'::jsonb`);
    case 'name':
      return unlessNull(c, `'Osoba ' || upper(${hash('id', 4)})`);
    case 'first_name':
      return unlessNull(c, `'Osoba'`);
    case 'last_name':
      return unlessNull(c, `upper(${hash('id', 4)})`);
    case 'name_profile':
      return unlessNull(
        c,
        `CASE WHEN is_teacher THEN 'Nauczyciel' WHEN is_parent THEN 'Rodzic' WHEN is_admin THEN 'Admin' ` +
          `ELSE 'Uczeń' END || ' ' || upper(${hash('id', 4)})`
      );
    case 'email_profile':
      // Same address as auth.users gets in anonymize-auth.sql, so sign-in and
      // the shadow-claim match keep working on the copy.
      return unlessNull(c, email('u', 'coalesce(user_id, id)'));
    case 'email_invite':
      return unlessNull(c, email('i', 'id'));
    case 'email_parent':
      return unlessNull(c, email('parent', 'id'));
  }
}

function assertIdent(name: string): string {
  if (!IDENT.test(name)) throw new Error(`unsafe identifier: ${name}`);
  return name;
}

/** Tables to truncate and per-table SET lists, validated. */
export function plan(rules: Rules) {
  const truncate: string[] = [];
  const updates: Array<{ table: string; sets: string[] }> = [];
  for (const [table, rule] of Object.entries(rules.tables)) {
    assertIdent(table);
    if ('truncate' in rule) {
      truncate.push(table);
      continue;
    }
    const all = Object.values(rule).flat() as string[];
    const sets: string[] = [];
    for (const [action, columns] of Object.entries(rule) as Array<[Action, string[]]>) {
      if (!ACTIONS.includes(action)) throw new Error(`${table}: unknown action ${action}`);
      for (const column of columns) {
        const expr = expressionFor(action, assertIdent(column));
        if (expr && /\bid\b/.test(expr) && !all.includes('id')) {
          throw new Error(`${table}.${column}: action ${action} needs an id column`);
        }
        if (expr) sets.push(`"${column}" = ${expr}`);
      }
    }
    if (sets.length) updates.push({ table, sets });
  }
  return { truncate, updates };
}

export function buildAnonymizeSql(rules: Rules, authSql: string): string {
  const { truncate, updates } = plan(rules);
  return [
    '-- Generated by scripts/test-stack/anonymize.ts from anonymize.rules.json. Do not edit.',
    '\\set ON_ERROR_STOP on',
    'BEGIN;',
    '-- No triggers: no audit rows carrying the old values, no notifications, no updated_at churn.',
    'SET LOCAL session_replication_role = replica;',
    truncate.length ? `TRUNCATE ${truncate.map((t) => `public."${t}"`).join(', ')};` : '',
    ...updates.map((u) => `UPDATE public."${u.table}" SET\n  ${u.sets.join(',\n  ')};`),
    authSql.trim(),
    'COMMIT;',
    '',
  ].join('\n');
}

/** Every column the database has that the rules do not classify, as `table.column`. */
export function unclassified(rules: Rules, schema: Record<string, string[]>): string[] {
  const missing: string[] = [];
  for (const [table, columns] of Object.entries(schema)) {
    const parent = Object.entries(rules.partitions).find(([, re]) =>
      new RegExp(re).test(table)
    )?.[0];
    const rule = rules.tables[parent ?? table];
    if (!rule) {
      missing.push(`${table}.*`);
      continue;
    }
    if ('truncate' in rule) continue;
    const listed = new Set(Object.values(rule).flat());
    for (const c of columns) if (!listed.has(c)) missing.push(`${table}.${c}`);
  }
  return missing;
}

// ─── Lessons ──────────────────────────────────────────────────────────────────

section('Lessons — completed history, then this week');
write(
  'create temp table _lessons(email text, idx int, number int, status text, scheduled_at timestamptz, title text, notes text) on commit drop;'
);

const lessonRows: string[] = [];
for (const student of STUDENTS) {
  const notes = STUDENT_LESSONS[student.email] ?? [];
  notes.forEach((lesson, i) => {
    const weeksAgo = notes.length - i;
    lessonRows.push(
      `  (${lit(student.email)}, ${i}, ${i + 1}, 'COMPLETED', ${ts(
        daysFromNow(-(weeksAgo * 7))
      )}, ${lit(lessonTitleFromNotes(lesson.notes))}, ${lit(lesson.notes)})`
    );
  });
}
write('insert into _lessons (email, idx, number, status, scheduled_at, title, notes) values');
write(lessonRows.join(',\n') + ';');

write();
write('-- Recover the generated ids by (student, scheduled_at): each historical');
write('-- lesson sits in its own week, so that pair is unique.');
write('create temp table _lesson_ids(email text, idx int, lesson_id uuid) on commit drop;');
write('with ins as (');
write(
  '  insert into public.lessons (teacher_id, student_id, lesson_teacher_number, status, scheduled_at, title, notes)'
);
write(`  select (select profile_id from _ids where email = ${lit(TEACHER.email)}), i.profile_id,`);
write('         l.number, l.status::public.lesson_status, l.scheduled_at, l.title, l.notes');
write('    from _lessons l join _ids i on i.email = l.email');
write('  returning id, student_id, scheduled_at');
write(')');
write('insert into _lesson_ids (email, idx, lesson_id)');
write('select l.email, l.idx, ins.id');
write('  from ins');
write('  join _ids i on i.profile_id = ins.student_id');
write('  join _lessons l on l.email = i.email and l.scheduled_at = ins.scheduled_at;');

// This week
const now = new Date();
const weekStart = new Date(now);
weekStart.setDate(now.getDate() - now.getDay());
weekStart.setHours(0, 0, 0, 0);

const weekRows = THIS_WEEK_SCHEDULE.map((l) => {
  const date = new Date(weekStart);
  date.setDate(weekStart.getDate() + l.dow);
  date.setHours(l.hour, 0, 0, 0);
  const isPast = l.dow < now.getDay() || (l.dow === now.getDay() && l.hour <= now.getHours());
  return `  (${lit(l.email)}, ${lit(isPast ? 'COMPLETED' : 'SCHEDULED')}, ${ts(date)}, ${lit(
    lessonTitleFromNotes(l.notes)
  )}, ${lit(l.notes)})`;
});

write();
write(
  'create temp table _week(email text, status text, scheduled_at timestamptz, title text, notes text) on commit drop;'
);
write('insert into _week (email, status, scheduled_at, title, notes) values');
write(weekRows.join(',\n') + ';');
write();
write('-- lesson_teacher_number 0 lets the numbering trigger own it, as the');
write('-- PostgREST seed does for this-week rows.');
write(
  'insert into public.lessons (teacher_id, student_id, lesson_teacher_number, status, scheduled_at, title, notes)'
);
write(`select (select profile_id from _ids where email = ${lit(TEACHER.email)}), i.profile_id,`);
write('       0, w.status::public.lesson_status, w.scheduled_at, w.title, w.notes');
write('  from _week w join _ids i on i.email = w.email;');

// ─── Lesson songs ─────────────────────────────────────────────────────────────

section('Lesson songs (student_repertoire follows by trigger)');
const lessonSongRows: string[] = [];
for (const student of STUDENTS) {
  const perLesson = LESSON_SONGS_BY_STUDENT[student.email] ?? [];
  perLesson.forEach((specs, idx) => {
    for (const spec of specs) {
      lessonSongRows.push(
        `  (${lit(student.email)}, ${idx}, ${lit(spec.title)}, ${lit(spec.status)})`
      );
    }
  });
}
write(
  'create temp table _lesson_songs(email text, idx int, title text, status text) on commit drop;'
);
write('insert into _lesson_songs (email, idx, title, status) values');
write(lessonSongRows.join(',\n') + ';');
write();
write('insert into public.lesson_songs (lesson_id, song_id, status)');
write('select li.lesson_id, m.song_id, ls.status::public.lesson_song_status');
write('  from _lesson_songs ls');
write('  join _lesson_ids li on li.email = ls.email and li.idx = ls.idx');
write('  join _song_map m on m.title = ls.title;');

// ─── Assignments ──────────────────────────────────────────────────────────────

section('Assignments');
const assignmentRows: string[] = [];
for (const student of STUDENTS) {
  for (const a of ASSIGNMENTS_BY_STUDENT[student.email] ?? []) {
    assignmentRows.push(
      `  (${lit(student.email)}, ${lit(a.title)}, ${lit(a.description)}, ${lit(a.status)}, ${ts(
        daysFromNow(a.dueDaysFromNow)
      )}::date)`
    );
  }
}
write(
  'create temp table _assignments(email text, title text, description text, status text, due_date date) on commit drop;'
);
write('insert into _assignments (email, title, description, status, due_date) values');
write(assignmentRows.join(',\n') + ';');
write();
write(
  'insert into public.assignments (teacher_id, student_id, title, description, status, due_date)'
);
write(`select (select profile_id from _ids where email = ${lit(TEACHER.email)}), i.profile_id,`);
write('       a.title, a.description, a.status::public.assignment_status, a.due_date');
write('  from _assignments a join _ids i on i.email = a.email;');

// ─── Practice ─────────────────────────────────────────────────────────────────

section('Practice sessions');
const practiceRows: string[] = [];
for (const student of STUDENTS) {
  const repertoire = (LESSON_SONGS_BY_STUDENT[student.email] ?? []).flat().map((s) => s.title);
  (PRACTICE_PLAN[student.email] ?? []).forEach((p, i) => {
    const at = new Date();
    at.setDate(at.getDate() - p.daysAgo);
    at.setHours(17, 30, 0, 0);
    const title = repertoire.length ? repertoire[i % repertoire.length] : null;
    practiceRows.push(
      `  (${lit(student.email)}, ${lit(title)}, ${num(p.minutes)}, ${num(p.bpm)}, ${lit(
        p.note
      )}, ${ts(at)})`
    );
  });
}
write(
  'create temp table _practice(email text, song_title text, minutes int, bpm int, note text, at timestamptz) on commit drop;'
);
write('insert into _practice (email, song_title, minutes, bpm, note, at) values');
write(practiceRows.join(',\n') + ';');
write();
write(
  'insert into public.practice_sessions (student_id, song_id, duration_minutes, bpm_practiced, notes, created_at)'
);
write('select i.profile_id, m.song_id, p.minutes, p.bpm, p.note, p.at');
write('  from _practice p');
write('  join _ids i on i.email = p.email');
write('  left join _song_map m on m.title = p.song_title;');

// ─── Self ratings ─────────────────────────────────────────────────────────────

section('Repertoire self-ratings');
write('create temp table _ratings(email text primary key, rating int, note text) on commit drop;');
write('insert into _ratings (email, rating, note) values');
write(
  STUDENTS.map((s) => {
    const cfg = SELF_RATINGS[s.email];
    return `  (${lit(s.email)}, ${num(cfg?.rating)}, ${lit(cfg?.note)})`;
  }).join(',\n') + ';'
);
write();
write('-- Mirrors the PostgREST seed: the three most recent repertoire rows, the');
write('-- rating stepping down by one, and the note only on the first.');
write('with ranked as (');
write(
  '  select sr.id, r.email, r.rating, r.note, row_number() over (partition by sr.student_id order by sr.created_at desc) as rn'
);
write('    from public.student_repertoire sr');
write('    join _ids i on i.profile_id = sr.student_id');
write('    join _ratings r on r.email = i.email');
write(')');
write('update public.student_repertoire sr');
write('   set self_rating = greatest(1, ranked.rating - (ranked.rn - 1)::int),');
write('       self_rating_updated_at = now(),');
write('       student_notes = case when ranked.rn = 1 then ranked.note else null end');
write('  from ranked where ranked.id = sr.id and ranked.rn <= 3;');


// ─── SQL literal helpers ──────────────────────────────────────────────────────

const NULL = 'null';

/** Single-quoted literal with doubled quotes. */
function lit(value: string | null | undefined): string {
  if (value === null || value === undefined) return NULL;
  return `'${value.replace(/'/g, "''")}'`;
}

/** Dollar-quoted, for song lyrics: multi-line text full of punctuation. */
function longLit(value: string | null | undefined): string {
  if (value === null || value === undefined) return NULL;
  let tag = 'demo';
  while (value.includes(`$${tag}$`)) tag += 'x';
  return `$${tag}$${value}$${tag}$`;
}

function num(value: number | null | undefined): string {
  return value === null || value === undefined ? NULL : String(value);
}

function bool(value: boolean): string {
  return value ? 'true' : 'false';
}

function ts(date: Date): string {
  return `'${date.toISOString()}'::timestamptz`;
}

function daysFromNow(days: number): Date {
  const d = new Date();
  d.setDate(d.getDate() + days);
  return d;
}

function hoursAgo(hours: number): Date {
  return new Date(Date.now() - hours * 3_600_000);
}

const out: string[] = [];
const write = (line = '') => out.push(line);
const section = (title: string) => {
  write();
  write(`-- ${'═'.repeat(74)}`);
  write(`-- ${title}`);
  write(`-- ${'═'.repeat(74)}`);
};

const TEACHER = DEMO_USERS.find((u) => u.isTeacher)!;
const STUDENTS = DEMO_USERS.filter((u) => u.isStudent);

// ─── Preamble ─────────────────────────────────────────────────────────────────

write('-- GENERATED by scripts/database/seeding/demo/emit-demo-sql.ts — do not edit.');
write(`-- Generated at ${new Date().toISOString()}`);
write('--');
write("-- Idempotent: re-running replaces this cohort's demo content and leaves");
write('-- every other row in the database alone. Songs are never overwritten.');
write('\\set ON_ERROR_STOP on');
write('begin;');

section('Demo people');
write(
  'create temp table _people(email text primary key, full_name text, is_teacher boolean, is_student boolean) on commit drop;'
);
write('insert into _people (email, full_name, is_teacher, is_student) values');
write(
  DEMO_USERS.map(
    (u) => `  (${lit(u.email)}, ${lit(u.fullName)}, ${bool(u.isTeacher)}, ${bool(u.isStudent)})`
  ).join(',\n') + ';'
);

write();
write('-- Create any missing account through auth.users + auth.identities, the same');
write('-- pair GoTrue itself writes. The handle_new_user trigger fires on the insert');
write('-- and mints the profile, so it is never built by hand here.');
write('with created as (');
write('  insert into auth.users (id, instance_id, aud, role, email, encrypted_password,');
write(
  '                          email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at)'
);
write("  select gen_random_uuid(), '00000000-0000-0000-0000-000000000000',");
write("         'authenticated', 'authenticated', p.email,");
write(`         crypt(${lit(DEMO_PASSWORD)}, gen_salt('bf')), now(),`);
write('         \'{"provider":"email","providers":["email"]}\'::jsonb,');
write("         jsonb_build_object('full_name', p.full_name), now(), now()");
write('    from _people p');
write('   where not exists (select 1 from auth.users u where u.email = p.email)');
write('  returning id, email');
write(')');
write(
  'insert into auth.identities (id, user_id, provider_id, provider, identity_data, created_at, updated_at, last_sign_in_at)'
);
write("select gen_random_uuid(), c.id, c.id::text, 'email',");
write(
  "       jsonb_build_object('sub', c.id::text, 'email', c.email, 'email_verified', true, 'phone_verified', false),"
);
write('       now(), now(), now()');
write('  from created c;');

write();
write('-- Reset the password on accounts that already existed, so the credentials');
write('-- printed on the sign-in button are always the ones that work.');
write('update auth.users u');
write(`   set encrypted_password = crypt(${lit(DEMO_PASSWORD)}, gen_salt('bf')),`);
write('       email_confirmed_at = coalesce(u.email_confirmed_at, now()),');
write('       updated_at = now()');
write('  from _people p');
write(' where u.email = p.email;');

write();
write('-- A profile may be missing even when the account is not: production has');
write('-- five demo accounts whose profiles were deleted, which is what left the');
write('-- public "Try the demo" button signing people into an onboarding loop.');
write(
  'insert into public.profiles (user_id, email, full_name, is_teacher, is_student, is_admin, is_development)'
);
write('select u.id, p.email, p.full_name, p.is_teacher, p.is_student, false, true');
write('  from _people p join auth.users u on u.email = p.email');
write(' where not exists (select 1 from public.profiles pr where pr.user_id = u.id);');

write();
write('update public.profiles pr');
write('   set email = p.email, full_name = p.full_name,');
write('       is_teacher = p.is_teacher, is_student = p.is_student,');
write('       is_admin = false, is_development = true,');
write("       avatar_url = 'https://i.pravatar.cc/150?u=' || p.email");
write('  from _people p join auth.users u on u.email = p.email');
write(' where pr.user_id = u.id;');

write();
write('create temp table _ids(email text primary key, profile_id uuid) on commit drop;');
write('insert into _ids (email, profile_id)');
write('select p.email, pr.id from _people p');
write('  join auth.users u on u.email = p.email');
write('  join public.profiles pr on pr.user_id = u.id;');

write();
write('do $guard$ begin');
write(
  `  if (select count(*) from _ids) <> ${DEMO_USERS.length} then raise exception 'expected ${DEMO_USERS.length} demo profiles, got %', (select count(*) from _ids); end if;`
);
write('end $guard$;');

// ─── Songs ────────────────────────────────────────────────────────────────────

section('Songs — link to the catalogue, fill only the gaps');
const SONG_COLUMNS = [
  'author',
  'level',
  'key',
  'tempo',
  'capo_fret',
  'chords',
  'strumming_pattern',
  'category',
  'release_year',
  'youtube_url',
  'spotify_link_url',
  'ultimate_guitar_link',
  'lyrics_with_chords',
] as const;

write(
  'create temp table _songs(title text primary key, author text, level text, key text, tempo int,'
);
write('  capo_fret int, chords text, strumming_pattern text, category text, release_year int,');
write(
  '  youtube_url text, spotify_link_url text, ultimate_guitar_link text, lyrics_with_chords text) on commit drop;'
);
write('insert into _songs values');
write(
  DEMO_SONGS.map((s) => {
    const row = s as Record<string, unknown>;
    return `  (${lit(s.title)}, ${lit(row.author as string)}, ${lit(row.level as string)}, ${lit(
      row.key as string
    )}, ${num(row.tempo as number)}, ${num(row.capo_fret as number)}, ${lit(
      row.chords as string
    )}, ${lit(row.strumming_pattern as string)}, ${lit(row.category as string)}, ${num(
      row.release_year as number
    )}, ${lit(row.youtube_url as string)}, ${lit(row.spotify_link_url as string)}, ${lit(
      row.ultimate_guitar_link as string
    )}, ${longLit(row.lyrics_with_chords as string)})`;
  }).join(',\n') + ';'
);

write();
write('-- Several catalogue rows can share a title. Take the richest one — that is');
write("-- the teacher's real entry — and never write over a column it already answers.");
write('create temp table _song_map(title text primary key, song_id uuid) on commit drop;');
write('insert into _song_map (title, song_id)');
write('select distinct on (s.title) s.title, s.id');
write('  from public.songs s join _songs d on d.title = s.title');
write(' where s.deleted_at is null');
write(
  ` order by s.title, num_nonnulls(${SONG_COLUMNS.map((c) => `s.${c}`).join(', ')}) desc, s.created_at asc;`
);

write();
write('insert into public.songs (title, author, level, key, tempo, capo_fret, chords,');
write('                          strumming_pattern, category, release_year, youtube_url,');
write('                          spotify_link_url, ultimate_guitar_link, lyrics_with_chords)');
write(
  'select d.title, d.author, d.level::public.difficulty_level, d.key::public.music_key, d.tempo,'
);
write('       d.capo_fret, d.chords, d.strumming_pattern, d.category, d.release_year,');
write('       d.youtube_url, d.spotify_link_url, d.ultimate_guitar_link, d.lyrics_with_chords');
write('  from _songs d');
write(' where not exists (select 1 from _song_map m where m.title = d.title);');

write();
write('insert into _song_map (title, song_id)');
write('select s.title, s.id from public.songs s join _songs d on d.title = s.title');
write(' where not exists (select 1 from _song_map m where m.title = s.title)');
write('on conflict (title) do nothing;');

write();
write('update public.songs s set');
write(
  SONG_COLUMNS.map((c) => {
    const cast =
      c === 'level' ? '::public.difficulty_level' : c === 'key' ? '::public.music_key' : '';
    return `  ${c} = coalesce(s.${c}, d.${c}${cast})`;
  }).join(',\n')
);
write('  from _songs d join _song_map m on m.title = d.title');
write(' where s.id = m.song_id;');


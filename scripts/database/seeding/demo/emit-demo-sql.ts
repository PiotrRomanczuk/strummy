/**
 * Renders the demo studio as a single idempotent SQL script.
 *
 * `seed-demo.ts` is the normal path and writes over PostgREST with a
 * service-role key. That path is unavailable on a self-hosted stack whose key
 * you cannot read — which is exactly the situation on `uwh`, where the only
 * channel to StudentProduction is `docker exec … psql`. Rather than maintain a
 * second copy of the dataset (the drift `.claude/rules/structure.md` S4 is
 * about), both transports read `demo-studio.data.ts` and this one prints SQL.
 *
 *   npx tsx scripts/database/seeding/demo/emit-demo-sql.ts > /tmp/demo.sql
 *   docker exec -i supabase_db_StudentProduction psql -U postgres -d postgres < /tmp/demo.sql
 *
 * Every timestamp is resolved here, not in SQL, so the output is a plain data
 * script with no date arithmetic to get subtly wrong in two languages. The only
 * things left for the database to resolve are the ids it alone knows: profile
 * ids (by email) and song ids (by title).
 */

